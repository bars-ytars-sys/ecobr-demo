import type { ImageMetadata } from 'astro';

const all = import.meta.glob<{ default: ImageMetadata }>('../assets/v2/*/*.{webp,jpg,png}', { eager: true });
export const img = (block: string, n: number): ImageMetadata => {
  const key = Object.keys(all).find((k) => k.includes(`/v2/${block}/${block}-${String(n).padStart(2, '0')}.`));
  if (!key) throw new Error(`Нет картинки ${block}-${n}`);
  return all[key]!.default;
};

